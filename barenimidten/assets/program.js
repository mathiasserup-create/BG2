/* ---- Program-renderer ---- */
(function(){
  var DATA = window.SNAPSTING_PROGRAM || {};
  var STAGE_COLORS = {
    "Nytorv":        "#f4a712",
    "Hjultorvet":    "#2f7d4f",
    "Paradepladsen": "#6b2c57"
  };
  var root = document.getElementById("program-app");
  if(!root) return;

  var stages = Object.keys(DATA);
  // saml alle dage på tværs i kronologisk rækkefølge
  var ORDER = ["Fredag 19/6","Lørdag 20/6","Søndag 21/6","Mandag 22/6",
    "Tirsdag 23/6","Onsdag 24/6","Torsdag 25/6","Fredag 26/6","Lørdag 27/6"];
  var allDays = ORDER.filter(function(d){
    return stages.some(function(s){ return DATA[s][d]; });
  });

  var state = { stage: "Alle", day: "Alle" };

  function el(tag, cls, html){
    var e=document.createElement(tag); if(cls)e.className=cls;
    if(html!=null)e.innerHTML=html; return e;
  }

  function renderStageList(stage, day){
    var days = DATA[stage] || {};
    var dayKeys = allDays.filter(function(d){
      return days[d] && (day==="Alle" || d===day);
    });
    if(!dayKeys.length) return null;

    var box = el("div");
    var h = el("div","stage-h");
    var dot = el("span","dot"); dot.style.background = STAGE_COLORS[stage]||"#999";
    h.appendChild(dot);
    h.appendChild(el("h2",null,stage));
    box.appendChild(h);

    dayKeys.forEach(function(d){
      var g = el("div","daygroup");
      g.appendChild(el("h3",null,d));
      var ul = el("ul","prog");
      days[d].forEach(function(it){
        var li = el("li", it.kind);
        li.appendChild(el("span","t", it.time||""));
        li.appendChild(el("span","a", it.act));
        ul.appendChild(li);
      });
      g.appendChild(ul);
      box.appendChild(g);
    });
    return box;
  }

  function render(){
    var out = el("div");
    var shown = state.stage==="Alle" ? stages : [state.stage];
    var any=false;
    shown.forEach(function(s){
      var node = renderStageList(s, state.day);
      if(node){ out.appendChild(node); any=true; }
    });
    if(!any) out.appendChild(el("p","note","Der er ikke noget program for det valgte – prøv en anden dag eller plads."));
    var host = document.getElementById("program-list");
    host.innerHTML=""; host.appendChild(out);
  }

  function chip(label, active, on){
    var b = el("button","chip"+(active?" active":""), label);
    b.addEventListener("click", on);
    return b;
  }

  function controls(){
    var sb = el("div","stagebar");
    sb.appendChild(chip("Alle pladser", state.stage==="Alle", function(){state.stage="Alle";build();}));
    stages.forEach(function(s){
      sb.appendChild(chip(s, state.stage===s, function(){state.stage=s;build();}));
    });
    var db = el("div","daybar");
    db.appendChild(chip("Alle dage", state.day==="Alle", function(){state.day="Alle";build();}));
    allDays.forEach(function(d){
      db.appendChild(chip(d, state.day===d, function(){state.day=d;build();}));
    });
    var wrap = el("div");
    wrap.appendChild(el("p","pill","Vælg plads"));
    wrap.appendChild(sb);
    wrap.appendChild(el("p","pill","Vælg dag"));
    wrap.appendChild(db);
    return wrap;
  }

  function build(){
    var c = document.getElementById("program-controls");
    c.innerHTML=""; c.appendChild(controls());
    render();
  }

  build();
})();
